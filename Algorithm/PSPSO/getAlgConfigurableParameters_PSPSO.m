function ConfigurableParameters = getAlgConfigurableParameters_PSPSO()
    % w: Inertia weight (multiplies the whole velocity sum, like a constriction factor).
    ConfigurableParameters.w = struct( ...
        'value', 0.6, ...
        'type', 'numeric', ...
        'range', [0, 2], ...
        'description', 'Inertia weight applied to the PSO velocity update.');

    % c1: Cognitive coefficient influencing personal best attraction.
    ConfigurableParameters.c1 = struct( ...
        'value', 2.83, ...
        'type', 'numeric', ...
        'range', [0, 5], ...
        'description', 'Coefficient scaling the influence of each particle''s personal best.');

    % c2: Social coefficient influencing global best attraction.
    ConfigurableParameters.c2 = struct( ...
        'value', 2.83, ...
        'type', 'numeric', ...
        'range', [0, 5], ...
        'description', 'Coefficient scaling the influence of the sub-swarm''s best position.');

    % SwarmNumber: Number of sub-swarms at initialization.
    ConfigurableParameters.SwarmNumber = struct( ...
        'value', 10, ...
        'type', 'integer', ...
        'range', [1, 100], ...
        'description', 'Number of sub-swarms at initialization (population size = SwarmNumber * SwarmSize).');

    % SwarmSize: Number of particles per species.
    ConfigurableParameters.SwarmSize = struct( ...
        'value', 7, ...
        'type', 'integer', ...
        'range', [1, 100], ...
        'description', 'Number of particles per sub-swarm formed by speciation.');

    % ConvergenceLimit: Radius threshold (per sqrt(Dimension)) to declare sub-swarm convergence.
    ConfigurableParameters.ConvergenceLimit = struct( ...
        'value', 0.01, ...
        'type', 'numeric', ...
        'range', [0, 1], ...
        'description', 'Radius threshold, multiplied by sqrt(Dimension), below which a sub-swarm is deactivated.');

    % DiversityDegree: Minimum active proportion before adding new particles.
    ConfigurableParameters.DiversityDegree = struct( ...
        'value', 0.7, ...
        'type', 'numeric', ...
        'range', [0, 1], ...
        'description', 'Minimum ratio of active particles to the initial population before diversity is restored.');

    % PerturbationFactor: Perturbation range as a fraction of the search range.
    ConfigurableParameters.PerturbationFactor = struct( ...
        'value', 0.025, ...
        'type', 'numeric', ...
        'range', [0, 1], ...
        'description', 'Velocity perturbation range as a fraction of the search range.');
end
